"""Q3 (METHODOLOGY D36): merged human PRs that build AI features, by keyword on the title and the cleaned body.

Bodies are cleaned first: lines about AI *use* (co-author trailers, "generated with", tool names, disclosure
sentences) and template checkboxes are removed, so AI-assisted coding (question 1) is not counted as an AI
feature (question 3). Bare "embedding" and "prompt" are excluded (iframe embeds, UI prompts).
Exploratory precision on partial data: ~85% title matches, ~83% body-only matches (hand read, 2026-10-29).

  python -I scripts/03f_ai_feature_prs.py   -> data/ai_feature_prs.csv (one row per matched PR)
                                               data/ai_feature_prs_yearly.csv (all merged human PRs, by year)
"""
import json, re, sys
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
FEAT = re.compile(r"chat\s?bot|\bllms?\b|large language model|\bgpt-?\d|openai|langchain|llama ?index|\brag\b|retrieval[- ]augmented|"
                  r"(?:text|vector|sentence|word) embeddings?|embedding (?:model|vector)s?|vector (?:db|store|search)|generative ai|genai|"
                  r"virtual assistant|conversational ai|ai assistant|\bai[- ](?:chat|agent|summar|generat|powered|feature|model|service)|"
                  r"speech[- ]to[- ]text|text[- ]to[- ]speech|\bwhisper\b|\bollama\b|mistral|"
                  r"machine[- ]learning|deep learning|neural net|tensorflow|pytorch|scikit|sklearn|hugging ?face|\bnlp\b|"
                  r"natural language processing|computer vision|image recognition|object detection|xgboost|random forest|"
                  r"predictive model|classification model|train(?:ed|ing)? (?:a |the )?model", re.I)
DROP_LINE = re.compile(r"co-authored-by|generated with|\U0001F916|noreply@anthropic|copilot|claude|cursor|chatgpt|codex|"
                       r"ai[- ](?:assist|generat|tool|use|usage|disclos|help)|(?:used|using|with the help of) (?:an? )?(?:ai|llm)|"
                       r"^\s*[-*]?\s*\[[ xX]\]|checklist|pull request template|"
                       r"generated by (?:an? )?(?:ai|llm)|comments are generated|evaluated accordingly|"
                       r"written by (?:an? )?(?:ai|llm|\S*bot)|\bbot\b.*\bllm\b|\bllm\b.*\bbot\b", re.I)
# AI in the development process, not the product (D48): applies to titles and body lines
DEVPROC = re.compile(r"agents?\.md|claude\.md|copilot[- ]instructions|cursor ?rules|\.cursorrules|ai[- ](?:agent|coding) (?:doc|guid|instruct|setup|config|rule)|"
                     r"ai (?:guidelines|policy|contribution)|ai[- ]assisted contributions|for ai agents|jetbrains|\.iml\b|"
                     r"(?:setup|instructions) for (?:ai|llm)|multi-agent isolation", re.I)
BOT = re.compile(r"\[bot\]$|^(dependabot|renovate|github-actions|pre-commit-ci|snyk-bot|weblate|transifex-integration|copilot|copilot-swe-agent)$", re.I)


def clean(body):
    return "\n".join(l for l in (body or "").splitlines() if not (DROP_LINE.search(l) or DEVPROC.search(l)))


def main():
    a = pd.read_csv(ROOT / "data/all_repos.csv", low_memory=False).drop_duplicates("full_name")
    tier = {r.full_name.lower(): (r.dpgid, r.dpg, r.confidence) for r in a.itertuples() if r.confidence in ("high", "medium")}
    hits, allrows = [], []
    for f in (ROOT / "cache").glob("*__*.json"):
        if f.name.startswith(("_", "inv_")): continue
        d = json.loads(f.read_text(encoding="utf-8"))
        key = d.get("full_name", "").lower()
        if d.get("status") != "ok" or key not in tier: continue
        dpgid, dpg, conf = tier[key]
        for p in d.get("prs") or []:
            if p.get("state") != "MERGED" or not p.get("mergedAt") or p["mergedAt"] < "2020": continue
            au = p.get("author") or {}
            if au.get("__typename") == "Bot" or BOT.search(au.get("login") or ""): continue
            t, b = p.get("title") or "", clean(p.get("bodyText"))
            mt = None if DEVPROC.search(t) else FEAT.search(t)
            mb = FEAT.search(b)
            allrows.append((dpgid, conf, p["mergedAt"][:4], bool(mt or mb), bool(mt)))
            if mt or mb:
                m = mt or mb
                ctx = t if mt else b[max(0, mb.start() - 100): mb.end() + 100].replace("\n", " ")
                hits.append({"dpgid": dpgid, "dpg": dpg, "confidence": conf, "full_name": d["full_name"], "merged_at": p["mergedAt"],
                             "source": "title" if mt else "body", "term": m.group(0).lower(), "title": t, "context": ctx})
    pd.DataFrame(hits).sort_values(["dpg", "merged_at"]).to_csv(ROOT / "data/ai_feature_prs.csv", index=False)
    al = pd.DataFrame(allrows, columns=["dpgid", "confidence", "year", "any_hit", "title_hit"])
    y = al.groupby(["confidence", "year"]).agg(merged_prs=("any_hit", "size"), ai_feature_prs=("any_hit", "sum"), ai_feature_prs_title=("title_hit", "sum"),
                                               dpgs=("dpgid", "nunique")).reset_index()
    y["dpgs_with_ai_feature_pr"] = [al[(al.confidence == c) & (al.year == yr) & al.any_hit].dpgid.nunique() for c, yr in zip(y.confidence, y.year)]
    y.to_csv(ROOT / "data/ai_feature_prs_yearly.csv", index=False)
    print(f"{len(hits)} AI-feature PRs in {len({h['dpgid'] for h in hits})} DPGs; files written")


if __name__ == "__main__":
    main()
